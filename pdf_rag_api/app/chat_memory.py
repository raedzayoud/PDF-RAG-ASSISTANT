"""Read and write persistent conversational history in PostgreSQL."""

import uuid  # Type session identifiers as UUIDs.
from datetime import datetime  # Type timestamps returned to the API layer.

from sqlalchemy import func, select  # Build explicit SQLAlchemy 2.0 SELECT statements.
from sqlalchemy.orm import Session  # The short-lived SQLAlchemy connection/session wrapper.

from app.db_models import ChatMessageRow, ChatSessionRow  # The two database table models.


class ChatMemoryStore:
    """Keep previous chat turns so follow-up questions survive application restarts."""

    def create_session(self, db: Session) -> ChatSessionRow:
        """Create a blank conversation and save it to PostgreSQL."""
        conversation = ChatSessionRow()  # The database model generates a UUID and timestamp.
        db.add(conversation)  # Mark the new conversation for insertion.
        db.commit()  # Persist it so Angular can use the resulting ID.
        db.refresh(conversation)  # Read any values generated by the database, if needed.
        return conversation

    def find_session(self, db: Session, session_id: uuid.UUID) -> ChatSessionRow | None:
        """Return a chat session, or None if the supplied ID does not exist."""
        return db.get(ChatSessionRow, session_id)  # Query a row by its primary key.

    def list_sessions(self, db: Session, limit: int = 50) -> list[dict]:
        """Summarize recent conversations for the frontend sidebar, newest first."""
        statement = (
            select(
                ChatSessionRow.id,
                ChatSessionRow.created_at,
                func.count(ChatMessageRow.id),
            )
            .outerjoin(ChatMessageRow, ChatMessageRow.session_id == ChatSessionRow.id)
            .group_by(ChatSessionRow.id, ChatSessionRow.created_at)
            .order_by(ChatSessionRow.created_at.desc())
            .limit(limit)
        )
        summaries: list[dict] = []
        for session_id, created_at, message_count in db.execute(statement).all():
            title = self._first_user_message(db, session_id)
            summaries.append(
                {
                    "session_id": session_id,
                    "created_at": created_at,
                    "message_count": message_count,
                    "title": title[:60] if title else None,
                }
            )
        return summaries

    def _first_user_message(self, db: Session, session_id: uuid.UUID) -> str | None:
        """Use the first user message as the conversation title shown in the sidebar."""
        statement = (
            select(ChatMessageRow.content)
            .where(ChatMessageRow.session_id == session_id, ChatMessageRow.role == "user")
            .order_by(ChatMessageRow.created_at, ChatMessageRow.id)
            .limit(1)
        )
        return db.scalars(statement).first()

    def get_recent_history(
        self, db: Session, session_id: uuid.UUID, limit: int = 10
    ) -> list[dict[str, str]]:
        """Return recent messages in chronological order for the LLM prompt."""
        statement = (
            select(ChatMessageRow)  # Select stored user and assistant messages.
            .where(ChatMessageRow.session_id == session_id)  # Only use this conversation's history.
            .order_by(ChatMessageRow.created_at.desc(), ChatMessageRow.id.desc())  # Newest first for limiting.
            .limit(limit)  # Keep prompts small instead of sending unlimited history.
        )
        rows = list(db.scalars(statement).all())  # Execute the query and collect returned rows.
        rows.reverse()  # The model reads a conversation in chronological order, oldest first.
        return [{"role": row.role, "content": row.content} for row in rows]  # Use OpenAI's message shape.

    def get_messages(
        self, db: Session, session_id: uuid.UUID, limit: int = 100
    ) -> list[ChatMessageRow]:
        """Return the latest messages for a frontend history panel, oldest first."""
        statement = (
            select(ChatMessageRow)
            .where(ChatMessageRow.session_id == session_id)
            .order_by(ChatMessageRow.created_at.desc(), ChatMessageRow.id.desc())
            .limit(limit)
        )
        rows = list(db.scalars(statement).all())
        rows.reverse()
        return rows

    def save_turn(
        self, db: Session, session_id: uuid.UUID, question: str, answer: str
    ) -> None:
        """Persist the user question and assistant answer in one database transaction."""
        db.add_all(
            [
                ChatMessageRow(session_id=session_id, role="user", content=question),
                ChatMessageRow(session_id=session_id, role="assistant", content=answer),
            ]
        )  # Both messages are stored together so the history remains consistent.
        db.commit()  # Commit this completed turn to persistent storage.
